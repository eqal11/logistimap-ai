"""Run with backend venv Python from project root to lock the installed runtime closure."""
from importlib import metadata
from pathlib import Path
from packaging.requirements import Requirement

root = Path(__file__).resolve().parents[1]
pending = [Requirement(line) for line in (root / "backend/requirements.txt").read_text().splitlines() if line and not line.startswith("#")]
seen = set()
versions = {}
while pending:
    req = pending.pop()
    key = (req.name.lower(), tuple(sorted(req.extras)))
    if key in seen:
        continue
    seen.add(key)
    dist = metadata.distribution(req.name)
    versions[dist.metadata["Name"]] = dist.version
    for dependency in dist.requires or []:
        parsed = Requirement(dependency)
        if not parsed.marker or any(parsed.marker.evaluate({"extra": extra}) for extra in (req.extras or {""})):
            pending.append(parsed)
out = "# Exact installed runtime dependencies; generated by scripts/lock-backend.py.\n"
out += "\n".join(f"{name}=={version}" for name, version in sorted(versions.items(), key=lambda item: item[0].lower())) + "\n"
(root / "backend/requirements.lock.txt").write_text(out, encoding="utf-8")
print("Locked", len(versions), "runtime dependencies")
